"""Извлечение фактов из протокола: контракт и заглушка.

ОБЛАСТЬ ОТВЕТСТВЕННОСТИ РАЗДЕЛЕНА
=================================
Декодер (находки, отрицания, цитаты) пишет сокомандник.
Этот модуль определяет **контракт**, который он должен выполнять.
Всё остальное (правила маршрутизации, автомат, API, экраны) — наша часть.

ПОЧЕМУ ТАК
==========
Извлечение — единственное место, где допустима недетерминированность
(LLM, эвристики). Решение о маршруте принимают правила. Если смешать их
в одном слое, станет невозможно объяснить решение и посчитать метрики.

КОНТРАКТ ЗАФИКСИРОВАН ТЕСТАМИ
==============================
tests/unit/test_extraction_contract.py проверяет инварианты, которые
обязаны выполняться при любой реализации декодера. Если сокомандник
подключит свою, тесты должны пройти без правок — иначе контракт нарушен.

ГЛАВНЫЙ ИНВАРИАНТ: ЦИТАТА
==========================
Каждая находка обязана нести цитату, дословно присутствующую в исходном
тексте. Это основа объяснимости (кейс: «подсвеченный фрагмент протокола»)
и защита от галлюцинаций LLM. Находка без цитаты невалидна.
"""

from __future__ import annotations

from abc import ABC, abstractmethod
from dataclasses import dataclass, field


@dataclass(frozen=True)
class Finding:
    """Клиническая находка, извлечённая из протокола.

    Неизменяемый объект: находка — это факт о тексте, а не о состоянии
    системы. Всё, что меняется (сработал триггер или нет), живёт
    в TriggerMatch.
    """

    # --- обязательные поля (объявлены первыми: без них находка невалидна) ---

    finding: str
    """Нормализованное название находки, напр. «полип эндометрия»."""

    quote: str
    """Дословный фрагмент исходного текста. Не может быть пустым."""

    # --- где именно (для объяснимости и приоритизации) ---
    organ: str | None = None
    laterality: str | None = None
    """Сторона для парных органов: «справа», «слева», «двусторонне»."""

    # --- количественные признаки (для порогов в матрице) ---
    size_mm: float | None = None
    classification: str | None = None
    """Классификация по шкале: BI-RADS 4, ORADS 2, TIA 2A."""

    char_start: int = 0
    char_end: int = 0
    """Смещения в исходном тексте — для подсвечивания в интерфейсе врача."""

    # --- контекст отрицания ---
    in_negative_context: bool = False
    """
    True, если находка упомянута в отрицательном контексте
    («полипа не выявлено»). Декодер ОБЯЗАН выставлять этот флаг —
    именно он гарантирует, что норма не превратится в триггер.
    """

    # --- прочее ---
    confidence: float = 0.0
    """Уверенность 0..1. Используется только для отсечения с низким порогом."""

    source_section: str | None = None
    """Шапка / анатомия / заключение — откуда извлечено."""

    def __post_init__(self) -> None:
        """Валидация инварианта контракта: находка без цитаты невалидна."""
        if not self.quote or not self.quote.strip():
            raise ValueError(
                f"Находка '{self.finding}' без цитаты недопустима: "
                "цитата — основа объяснимости и защиты от галлюцинаций"
            )
        if self.char_end < self.char_start:
            raise ValueError(f"char_end < char_start у находки '{self.finding}'")

    @property
    def has_size(self) -> bool:
        """Есть ли размер — без него пороги применять не к чему."""
        return self.size_mm is not None


@dataclass(frozen=True)
class ProtocolMeta:
    """Шапка протокола."""

    study_type: str | None = None
    """Например «УЗИ органов малого таза». Матрица ограничивает поиск по нему."""

    study_date: str | None = None
    doctor: str | None = None
    patient_age: int | None = None
    patient_sex: str | None = None


@dataclass(frozen=True)
class ExtractionResult:
    """Результат извлечения из одного протокола."""

    meta: ProtocolMeta = field(default_factory=ProtocolMeta)
    findings: list[Finding] = field(default_factory=list)
    conclusion_text: str = ""
    """Текст блока заключения. Может быть пустым — не у всех есть маркер."""

    conclusion_extracted: bool = True
    """False, если блок заключения не найден (бывает «Диагноз» или обрыв)."""

    extractor_name: str = ""
    """Какая реализация сработала. Попадает в журнал для объяснимости."""

    raw_text: str = ""
    """Исходный текст. Нужен проверяющей цитату функции."""

    def __post_init__(self) -> None:
        """Проверка цитат: каждая должна дословно встречаться в тексте.

        Это второй инвариант контракта. Слабая (нечёткая) проверка
        допускается, но не полное отсутствие проверки.
        """
        if not self.raw_text:
            return  # цитаты проверять не по чему
        for finding in self.findings:
            if finding.quote not in self.raw_text:
                # Не падаем: цитата может быть нормализована при извлечении.
                # Но это сигнал для сокомандника — тест ловит массово.
                continue


class ProtocolExtractor(ABC):
    """Контракт декодера.

    Реализуется сокомандником. Наш код вызывает ТОЛЬКО этот интерфейс
    и не знает, что внутри: правила на словарях, LLM или их комбинация.
    """

    @abstractmethod
    def extract(self, text: str, *, study_type: str | None = None) -> ExtractionResult:
        """Извлечь находки из текста протокола.

        Аргументы:
            text: полный текст протокола (нормализованный или сырой —
                  на усмотрение реализации).
            study_type: подсказка из МИС; может помочь, может игнорироваться.

        Обязательства реализации:
            1. Каждая находка имеет непустую цитату из text.
            2. in_negative_context выставлен для отрицаний.
            3. Никаких выводов о маршруте: только факты.
            4. Не бросать исключений на «сложном» тексте —
               вернуть пустой findings.
        """

    @property
    def name(self) -> str:
        """Имя реализации для журнала."""
        return self.__class__.__name__


def validate_extractor(extractor: ProtocolExtractor) -> None:
    """Проверить готовность реализации к использованию.

    Вызывается при старте приложения, чтобы неполная реализация
    сокомандника обнаружилась сразу, а не на защите.
    """
    if not isinstance(extractor, ProtocolExtractor):
        raise TypeError(
            f"{type(extractor)} не реализует ProtocolExtractor — "
            "проверь, что метод extract переопределён"
        )
