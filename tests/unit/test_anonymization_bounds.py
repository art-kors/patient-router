"""Границы значений персональных полей на реальных формулировках протокола.

Регрессия, которую закрывает этот файл: правило «Дата рождения» захватывало
не только дату, но и следующее клиническое поле «Возраст на момент осмотра»,
потому что граница искалась только по справочнику меток, а такой метки
в справочнике не было. Возраст и «лет» исчезали из текста, а длина сохранялась —
проверка «длина не изменилась» этого не замечала.
"""

import pytest

from app.services.anonymization import anonymize

# Фрагменты из настоящих протоколов: после снятия тегов Word поля слипаются
# в один абзац, метки идут подряд, между ними обычные пробелы.
СЛИПШИЙСЯ = (
    "Карта № 1 ЖП (1) Протокол ультразвукового исследования органов брюшной полости "
    "Дата приема: 07.09.2026 Время: 12:14 ФИО пациента: Дата рождения: 31.07.1987 "
    "Возраст на момент осмотра: 39 лет Врач: Ирина Олеговна ПЕЧЕНЬ Размеры: в пределах нормы."
)


@pytest.mark.parametrize(
    "клиника",
    [
        "Возраст на момент осмотра: 39 лет",
        "Пол: женский",
        "Диагноз: УЗ признаки",
        "Размеры: в пределах нормы",
        "BI-RADS: 3",
    ],
)
def test_клиническое_поле_не_съедается(клиника: str) -> None:
    """Персональное поле не должно заходить на соседние клинические поля."""
    исходник = f"Дата рождения: 31.07.1987 {клиника} Врач: Ирина Олеговна"
    текст, _ = anonymize(исходник)
    assert клиника in текст, f"потеряно клиническое поле: {клиника}"


@pytest.mark.parametrize(
    "метка",
    [
        "Возраст",
        "Возраст пациента",
        "Возраст на момент осмотра",
        "Возраст пациента на момент осмотра",
    ],
)
def test_возраст_переживает_все_написания_метки(метка: str) -> None:
    """Метка возраста может называться как угодно — возраст обязан выжить."""
    исходник = f"Дата рождения: 31.07.1987 {метка}: 39 лет Врач: Ирина Олеговна"
    текст, _ = anonymize(исходник)
    assert f"{метка}: 39 лет" in текст


def test_дата_рождения_закрыта_а_возраст_остался() -> None:
    """Главный случай регрессии: оба условия выполняются одновременно."""
    текст, _ = anonymize(СЛИПШИЙСЯ)
    assert "31.07.1987" not in текст, "дата рождения должна быть закрыта"
    assert "Возраст на момент осмотра: 39 лет" in текст, "возраст обязан остаться"


def test_длина_и_клинический_текст_вместе() -> None:
    """Проверка длины сама по себе не ловит регресс — нужна и проверка содержимого."""
    текст, _ = anonymize(СЛИПШИЙСЯ)
    assert len(текст) == len(СЛИПШИЙСЯ)
    assert "ПЕЧЕНЬ Размеры: в пределах нормы" in текст


def test_неизвестная_метка_тоже_останавливает_значение() -> None:
    """Граница не должна зависеть от наличия метки в справочнике."""
    исходник = "Дата рождения: 31.07.1987 Какая-то новая метка: значение Врач: Ирина Олеговна"
    текст, _ = anonymize(исходник)
    assert "Какая-то новая метка: значение" in текст
